import { writeFile } from "node:fs/promises";

// ADR-0031 §4：内置预设引用的 models.dev 服务商键（与
// packages/core/src/config/models-dev.ts 的 MODELS_DEV_PROVIDER_KEYS 保持一致）
const PROVIDER_KEYS = [
  "opencode",
  "opencode-go",
  "deepseek",
  "xai",
  "anthropic",
  "openai",
  "openrouter",
];

function trimCost(value) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return undefined;
  const result = {};
  for (const [from, to] of [
    ["input", "input"],
    ["output", "output"],
    ["cache_read", "cacheRead"],
    ["cache_write", "cacheWrite"],
  ]) {
    if (typeof value[from] === "number" && Number.isFinite(value[from]) && value[from] >= 0)
      result[to] = value[from];
  }
  if (Array.isArray(value.tiers))
    result.tiers = value.tiers.flatMap((t) => {
      const size = t?.tier?.size;
      if (!Number.isInteger(size) || size < 0) return [];
      return [{ aboveInputTokens: size, ...trimCost({ ...t, tiers: undefined }) }];
    });
  return Object.keys(result).length ? result : undefined;
}

const [response, apiResponse] = await Promise.all([
  fetch("https://models.dev/models.json", { signal: AbortSignal.timeout(10_000) }),
  fetch("https://models.dev/api.json", { signal: AbortSignal.timeout(10_000) }),
]);
if (!response.ok) throw new Error(`models.dev HTTP ${response.status}`);
const raw = await response.json();
const models = Object.fromEntries(
  Object.entries(raw).map(([id, value]) => [
    id,
    {
      ...(typeof value.reasoning === "boolean" ? { reasoning: value.reasoning } : {}),
      ...(Array.isArray(value.modalities?.input)
        ? { input: value.modalities.input.filter((x) => typeof x === "string") }
        : {}),
      ...(Number.isInteger(value.limit?.context) && value.limit.context > 0
        ? { context: value.limit.context }
        : {}),
      ...(Number.isInteger(value.limit?.output) && value.limit.output > 0
        ? { output: value.limit.output }
        : {}),
    },
  ]),
);

// api.json：按服务商键保存 npm 原文（服务商级 + 逐模型 provider.npm；
// 模型条目记录存在性，npm 缺省为 {}）
let providers;
if (apiResponse.ok) {
  const api = await apiResponse.json();
  providers = {};
  for (const key of PROVIDER_KEYS) {
    const p = api[key];
    if (p === null || typeof p !== "object") continue;
    const entry = {
      ...(typeof p.npm === "string" ? { npm: p.npm } : {}),
      models: {},
    };
    for (const [modelId, mv] of Object.entries(p.models ?? {})) {
      const npm = mv !== null && typeof mv === "object" ? mv.provider?.npm : undefined;
      const cost = trimCost(mv?.cost);
      entry.models[modelId] = {
        ...(typeof npm === "string" && npm !== "" ? { npm } : {}),
        ...(cost !== undefined ? { cost } : {}),
      };
    }
    providers[key] = entry;
  }
  if (Object.keys(providers).length === 0) providers = undefined;
} else {
  console.warn(`api.json HTTP ${apiResponse.status}：快照不含 providers 块`);
}

const snapshot = {
  fetchedAt: new Date().toISOString(),
  models,
  ...(providers !== undefined ? { providers } : {}),
};
await writeFile(
  new URL("../packages/core/src/config/models-dev-snapshot.ts", import.meta.url),
  `// Generated by scripts/update-models-dev-snapshot.mjs; do not edit.\nexport const modelsDevSnapshot = ${JSON.stringify(snapshot)} as const;\n`,
);
console.log(`${Object.keys(models).length} models, ${snapshot.fetchedAt}`);
